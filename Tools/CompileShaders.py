"""Compiles GLWidgets' HLSL shaders for every GPU API and writes them as C++ headers, which are committed: building
GLWidgets needs no shader compiler, changing a shader does.

  DXBC   (Direct3D 12)  fxc, from the Windows SDK (found by itself on Windows)
  SPIR-V (Vulkan)       DXC built with SPIR-V code generation (the releases of microsoft/DirectXShaderCompiler, the
                        Vulkan SDK; not the dxc of the Windows SDK)
  MSL    (Metal)        SPIRV-Cross, from the SPIR-V

DXC and SPIRV-Cross are taken from the Vulkan SDK when it is installed (VULKAN_SDK, or the newest C:\\VulkanSDK\\<version>),
otherwise from PATH.

  python Tools/CompileShaders.py [--fxc PATH] [--dxc PATH] [--spirv-cross PATH] [--allow-missing]

Without --allow-missing every format must be compiled. With it, a format whose tool is missing is written empty: the
GPU APIs that take it cannot draw with that shader (Device::createShader throws).
"""
import argparse
import glob
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# name: the prefix of the C++ names; stages: (stage, entry point, profile prefix)
SHADERS = [
    {
        "name": "painter",
        "source": "Library/Shaders/Painter.hlsl",
        "output": "Library/Source/Paint/PainterShaders.hpp",
        "namespace": "glw::paint::shaders",
        "stages": [("Vertex", "vertexMain", "vs"), ("Fragment", "fragmentMain", "ps")],
    },
    {
        "name": "scene",
        "source": "Library/Shaders/Scene.hlsl",
        "output": "Library/Source/Paint/SceneShaders.hpp",
        "namespace": "glw::paint::shaders",
        "stages": [("Vertex", "vertexMain", "vs"), ("Fragment", "fragmentMain", "ps")],
    },
]


def find_fxc():
    found = shutil.which("fxc")
    if found:
        return found
    kits = os.path.join(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"), "Windows Kits", "10", "bin")
    candidates = sorted(glob.glob(os.path.join(kits, "10.*", "x64", "fxc.exe")))
    return candidates[-1] if candidates else None


def find_in_vulkan_sdk(tool):
    """`tool` of the Vulkan SDK (DXC there has SPIR-V code generation), or None."""
    roots = [os.environ["VULKAN_SDK"]] if os.environ.get("VULKAN_SDK") else []
    roots += sorted(glob.glob(r"C:\VulkanSDK\*"), reverse=True)
    for root in roots:
        for folder in ("Bin", "bin"):
            for name in (f"{tool}.exe", tool):
                path = os.path.join(root, folder, name)
                if os.path.isfile(path):
                    return path
    return None


def run(command):
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"failed: {' '.join(command)}\n{result.stdout}{result.stderr}")


def read(path):
    with open(path, "rb") as f:
        return f.read()


def compile_stage(tools, source, entry, profile, work):
    """The stage's code in each format there is a tool for: {"Dxbc": bytes, "Spirv": bytes, "Msl": bytes}."""
    code = {}
    if tools["fxc"]:
        out = os.path.join(work, f"{entry}.dxbc")
        run([tools["fxc"], "/nologo", "/T", f"{profile}_5_1", "/E", entry, "/O3", "/Fo", out, source])
        code["Dxbc"] = read(out)
    if tools["dxc"]:
        spv = os.path.join(work, f"{entry}.spv")
        run([tools["dxc"], "-spirv", "-fspv-target-env=vulkan1.0", "-T", f"{profile}_6_0", "-E", entry, "-Fo", spv, source])
        code["Spirv"] = read(spv)
        if tools["spirv_cross"]:
            msl = os.path.join(work, f"{entry}.metal")
            run([tools["spirv_cross"], spv, "--msl", "--msl-version", "20100", "--output", msl])
            code["Msl"] = read(msl)
    return code


def array(name, data):
    if not data:
        return f"inline constexpr std::span<const std::uint8_t> {name}{{}};\n"
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    return (f"inline constexpr std::uint8_t {name}Data[] = {{\n" + "\n".join(lines) + "\n};\n"
            f"inline constexpr std::span<const std::uint8_t> {name}{{{name}Data}};\n")


def write_header(shader, stages_code):
    missing = sorted({fmt for code in stages_code.values() for fmt in ("Dxbc", "Spirv", "Msl") if fmt not in code})
    text = ["// SPDX-FileCopyrightText: 2026 Abdolmanaf Mehrabi Sisakht\n",
            "// SPDX-License-Identifier: MIT\n",
            f"// Generated by Tools/CompileShaders.py from {shader['source']}: do not edit, run the script again.\n"]
    if missing:
        text.append(f"// Not compiled (a tool was missing): {', '.join(missing)}.\n")
    text += ["#pragma once\n", "#include <cstdint>\n", "#include <span>\n", "\n", f"namespace {shader['namespace']} {{\n", "\n"]
    for stage, code in stages_code.items():
        for fmt in ("Dxbc", "Spirv", "Msl"):
            text.append(array(f"{shader['name']}{stage}{fmt}", code.get(fmt, b"")))
        text.append("\n")
    text.append(f"}} // namespace {shader['namespace']}\n")
    path = os.path.join(ROOT, shader["output"])
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write("".join(text))
    print(f"wrote {shader['output']}" + (f" (without {', '.join(missing)})" if missing else ""))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--fxc", help="fxc.exe (default: from PATH or the Windows SDK)")
    parser.add_argument("--dxc", help="a dxc with SPIR-V code generation (default: from PATH)")
    parser.add_argument("--spirv-cross", help="spirv-cross (default: from PATH)")
    parser.add_argument("--allow-missing", action="store_true", help="write empty code for the formats without a tool")
    args = parser.parse_args()

    tools = {
        "fxc": args.fxc or find_fxc(),
        "dxc": args.dxc or find_in_vulkan_sdk("dxc") or shutil.which("dxc"),
        "spirv_cross": args.spirv_cross or find_in_vulkan_sdk("spirv-cross") or shutil.which("spirv-cross"),
    }
    absent = [name for name, path in tools.items() if not path]
    if absent and not args.allow_missing:
        sys.exit(f"missing: {', '.join(absent)} (give their paths, or --allow-missing)")

    with tempfile.TemporaryDirectory() as work:
        for shader in SHADERS:
            source = os.path.join(ROOT, shader["source"])
            stages_code = {stage: compile_stage(tools, source, entry, profile, work)
                           for stage, entry, profile in shader["stages"]}
            write_header(shader, stages_code)


if __name__ == "__main__":
    main()
